#!/usr/bin/env -S python3 -I
"""gen_sga4_shim.py -- build a pdfLaTeX stand-in for a LuaLaTeX macro file, for corpus testing only.

The English SGA 4 (translation/SGA4) is written for LuaLaTeX: its sga4-en.sty loads fontspec, polyglossia, unicode-math
and luatex85, and calls \\directlua.  rstex is pdfTeX-compatible and has no Lua, so as written the volume cannot compile.
It is still 3 MB of real mathematics, so this script derives a stand-in that makes the sources compile on pdflatex,
with the sources themselves unmodified.

Nothing of the owner's text lives in this file or in the repo.  It reads their .sty and their .tex at run time and
writes under target/corpus/, which is gitignored.  The stand-in is first in TEXINPUTS of the corpus entries, and LaTeX
tries the search path before \\input@path, so it wins over the original beside the document.

What the stand-in does:
- Drops the Lua and OpenType lines (asserting that each was found) and puts T1, utf8 inputenc, lmodern, babel, amssymb,
  mathrsfs and etoolbox in their place.  Every other line of the original passes through byte for byte.
- Declares every non-ASCII character the sources use that LaTeX has no default for and the table below can map.  A
  character the table cannot map stays undeclared: on pdflatex it is an error in the log and the run continues, which is
  still a valid differential test.  Unmapped characters are listed in the report.

The result is not the document the owner reads.  Fonts differ (Type 1 Latin Modern, not OpenType), so do line and page
breaks, and math-style=ISO is gone.  It tests pdfTeX fidelity on this body of mathematics and says nothing about how
faithful a rendering of SGA 4 it is.

The French originals (source/SGA4/SGA4_orig) have the same trouble and one more: they reach their configuration by the
relative path ../fichiers-configuration-latex/, which a search path cannot intercept.  --french writes stand-ins for
paquets.tex and macros.tex, and a prelude line in `prelude.txt` that a manifest entry uses to redirect those two names with
the kernel's file substitution.  babel-french is not installed on this machine, so the language stays English: French
hyphenation and captions are gone, and \\selectlanguage{french} does nothing.

    python3 -I tests/corpus/gen_sga4_shim.py [--sources DIR] [--out DIR]
    python3 -I tests/corpus/gen_sga4_shim.py --french [--sources DIR] [--out DIR]
"""
import argparse
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_SOURCES = os.path.expanduser('~/Projects/SlopdeGeometrieAlgebrique/translation/SGA4')
DEFAULT_OUT = os.path.join(REPO, 'target', 'corpus', 'sga4-shim')
DEFAULT_FR_SOURCES = os.path.expanduser('~/Projects/SlopdeGeometrieAlgebrique/source/SGA4/SGA4_orig/tree/SGA4-HEAD-71766d9')
DEFAULT_FR_OUT = os.path.join(REPO, 'target', 'corpus', 'sga4-fr-shim')
FR_CONFIG = '../fichiers-configuration-latex'

# Lines of the original that only make sense on LuaLaTeX.  Each pattern must match exactly the stated number of lines,
# so a change upstream stops the generator instead of silently producing something else.
DROP = [
    (r'\\RequirePackage\{luatex85\}', 1),
    (r'\\RequirePackage\{polyglossia\}', 1),
    (r'\\setmainlanguage\b', 1),
    (r'\\setotherlanguage\b', 1),
    (r'\\RequirePackage\{fontspec\}', 1),
    (r'\\RequirePackage\[[^]]*\]\{unicode-math\}', 1),
    (r'\\directlua\b', 1),
    (r'\\setmainfont\b', 1),
    (r'\\setmathfont\b', 2),
]

HEADER = r"""% --- pdfLaTeX stand-in, generated by tests/corpus/gen_sga4_shim.py.  For corpus testing only. ---
\RequirePackage[T1]{fontenc}
\RequirePackage[utf8]{inputenc}
\RequirePackage{lmodern}
\RequirePackage{etoolbox}
\RequirePackage[american]{babel}
\RequirePackage{amsmath}
\RequirePackage{amssymb}
\RequirePackage{mathrsfs}
"""

GREEK_LOWER = ['alpha', 'beta', 'gamma', 'delta', 'epsilon', 'zeta', 'eta', 'theta', 'iota', 'kappa', 'lambda', 'mu', 'nu',
               'xi', 'omicron', 'pi', 'rho', 'varsigma', 'sigma', 'tau', 'upsilon', 'phi', 'chi', 'psi', 'omega']


def braced(body):
    """A character that may stand alone after _ or ^.  \\ensuremath would expand to \\relax first, and that gives
    'Missing { inserted' in a subscript.  The braces make it one math field."""
    return '{\\ensuremath{' + body + '}}'


def bare(body):
    """A big operator or relation: braces would make it an ordinary atom and lose its limits or spacing."""
    return '\\ensuremath{' + body + '}'


def unicode_table():
    t = {}
    # Mathematical script capitals.  The holes of the block live in Letterlike Symbols.
    for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
        t[0x1D49C + i] = braced(f'\\mathcal{{{c}}}')
    for cp, c in {0x212C: 'B', 0x2130: 'E', 0x2131: 'F', 0x210B: 'H', 0x2110: 'I', 0x2112: 'L', 0x2133: 'M', 0x211B: 'R'}.items():
        t[cp] = braced(f'\\mathcal{{{c}}}')
    for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
        t[0x1D400 + i] = braced(f'\\mathbf{{{c}}}')                 # bold
        t[0x1D504 + i] = braced(f'\\mathfrak{{{c}}}')               # fraktur
    for i, c in enumerate('abcdefghijklmnopqrstuvwxyz'):
        t[0x1D41A + i] = braced(f'\\mathbf{{{c}}}')
        t[0x1D51E + i] = braced(f'\\mathfrak{{{c}}}')
    for cp, c in {0x2102: 'C', 0x210D: 'H', 0x2115: 'N', 0x2119: 'P', 0x211A: 'Q', 0x211D: 'R', 0x2124: 'Z'}.items():
        t[cp] = braced(f'\\mathbb{{{c}}}')
    upper = ['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon', 'Zeta', 'Eta', 'Theta', 'Iota', 'Kappa', 'Lambda', 'Mu', 'Nu', 'Xi',
             'Omicron', 'Pi', 'Rho', None, 'Sigma', 'Tau', 'Upsilon', 'Phi', 'Chi', 'Psi', 'Omega']
    latin_like = {'Alpha': 'A', 'Beta': 'B', 'Epsilon': 'E', 'Zeta': 'Z', 'Eta': 'H', 'Iota': 'I', 'Kappa': 'K', 'Mu': 'M', 'Nu': 'N',
                  'Omicron': 'O', 'Rho': 'P', 'Tau': 'T', 'Chi': 'X'}
    for i, name in enumerate(upper):                                # U+0391.. and bold U+1D6A8..
        if name is None:
            continue
        body = latin_like.get(name)
        plain = f'\\mathrm{{{body}}}' if body else f'\\{name}'
        bold = f'\\mathbf{{{body}}}' if body else f'\\boldsymbol{{\\{name}}}'
        t[0x391 + i] = braced(plain)
        t[0x1D6A8 + i] = braced(bold)
    for i, name in enumerate(GREEK_LOWER):                          # U+03B1.. and bold U+1D6C2..
        if name == 'omicron':
            t[0x3B1 + i] = braced('o')
            t[0x1D6C2 + i] = braced('\\mathbf{o}')
            continue
        t[0x3B1 + i] = braced(f'\\{name}')
        t[0x1D6C2 + i] = braced(f'\\boldsymbol{{\\{name}}}')
    t.update({
        0x2113: braced('\\ell'),
        0x2205: braced('\\varnothing'),
        0x2032: braced('{}^{\\prime}'),
        0x2219: braced('\\bullet'),
        0x22C5: braced('\\cdot'),
        0x2218: braced('\\circ'),
        0x2016: braced('\\|'),
        0x00D7: '\\ifmmode\\times\\else\\texttimes\\fi',
        0x21A6: bare('\\mapsto'),
        0x2264: bare('\\leq'),
        0x2265: bare('\\geq'),
        0x2A01: bare('\\bigoplus'),
        0x22C3: bare('\\bigcup'),
        0x22C2: bare('\\bigcap'),
        0x2192: bare('\\rightarrow'),
        0x2194: bare('\\leftrightarrow'),
        0x2210: bare('\\coprod'),
        0x221A: bare('\\surd'),
        0x2009: '\\,',
        0x1D52: '\\textsuperscript{o}',
        0x2080: braced('{}_{0}'),
        0x2070: braced('{}^{0}'),
        0x2190: bare('\\leftarrow'),
        0x2208: bare('\\in'),
        0x2211: bare('\\sum'),
        0x220F: bare('\\prod'),
        0x2297: bare('\\otimes'),
        0x2295: bare('\\oplus'),
        0x221E: braced('\\infty'),
    })
    return t


def latin1_and_friends(cp):
    """Characters LaTeX's utf8 and T1 or TS1 encodings define: no declaration needed."""
    return 0xA0 <= cp <= 0x17F or cp in (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026)


def scan_sources(root):
    """Every non-ASCII character of every .tex under root, with its count.  Lines read as UTF-8; bad bytes are counted."""
    found, bad, files, size = {}, 0, 0, 0
    for d, subdirs, names in os.walk(root):
        subdirs[:] = [s for s in subdirs if s not in ('tools', 'fichiers-configuration-latex') and not s.startswith('.')]
        for n in names:
            if not n.endswith('.tex'):
                continue
            files += 1
            with open(os.path.join(d, n), 'rb') as f:
                data = f.read()
            size += len(data)
            text = data.decode('utf-8', 'replace')
            bad += text.count('\ufffd')
            for ch in text:
                if ord(ch) > 127:
                    found[ord(ch)] = found.get(ord(ch), 0) + 1
    return found, bad, files, size


def transform(original):
    """The original with Lua and OpenType lines dropped, the header in the place of the first dropped line."""
    lines = original.split('\n')
    counts = [0] * len(DROP)
    out, header_done = [], False
    for line in lines:
        hit = None
        for i, (rx, _) in enumerate(DROP):
            if re.match(r'\s*' + rx, line):
                hit = i
                break
        if hit is None:
            # A math operator name holding an accented letter: in math mode \'e is an error, so spell it as a math accent.
            if line.lstrip().startswith('\\DeclareMathOperator') and re.search(r'[^\x00-\x7f]', line):
                line = line.replace('\u00e9', '\\acute{e}')
            out.append(line)
            continue
        counts[hit] += 1
        if not header_done:
            out.append(HEADER.rstrip('\n'))
            header_done = True
    for (rx, want), got in zip(DROP, counts):
        if want != got:
            sys.exit(f'gen_sga4_shim: {rx} matched {got} lines, expected {want}.  The original changed; review this script.')
    return '\n'.join(out)


def drop_lines(text, rules, where):
    """text without the lines matching rules [(regex, expected count)]; stops if a count is off."""
    counts = [0] * len(rules)
    out = []
    for line in text.split('\n'):
        for i, (rx, _) in enumerate(rules):
            if re.match(r'\s*' + rx, line):
                counts[i] += 1
                break
        else:
            out.append(line)
    for (rx, want), got in zip(rules, counts):
        if want != got:
            sys.exit(f'gen_sga4_shim: {where}: {rx} matched {got} lines, expected {want}.  The original changed; review this script.')
    return '\n'.join(out)


FR_HEADER = HEADER.replace('[american]{babel}', '[english]{babel}') + r"""\let\shimselectlanguage\selectlanguage
\def\selectlanguage#1{\ifstrequal{#1}{french}{}{\shimselectlanguage{#1}}}
\expandafter\let\csname l@french\expandafter\endcsname\csname l@english\endcsname
"""


def french(args):
    with open(os.path.join(args.sources, 'fichiers-configuration-latex', 'paquets.tex'), encoding='utf-8') as f:
        paquets = f.read()
    with open(os.path.join(args.sources, 'fichiers-configuration-latex', 'macros.tex'), encoding='utf-8') as f:
        macros = f.read()
    paquets = drop_lines(paquets, [(r'\\usepackage\{polyglossia\}', 1), (r'\\usepackage\{fontspec\}', 1),
                                   (r'\\usepackage\[[^]]*\]\{unicode-math\}', 1), (r'\\setmainlanguage\b', 1),
                                   (r'\\setmainfont\b', 1), (r'\\setmathfont\b', 1)], 'paquets.tex')
    # The Lua block prints the git status.  It lives between two \catcode changes of %.
    macros, n = re.subn(r'\\catcode`\\%=12\n\\directlua\{.*?\n\}\n\\catcode`\\%=14\n', '', macros, flags=re.S)
    if n != 1:
        sys.exit('gen_sga4_shim: macros.tex: the \\directlua block was not found once.')
    macros, n = re.subn(r'^\\def\\showgitstatus\{\\directlua\{git_status\(\)\}\}$', r'\\def\\showgitstatus{?}', macros, flags=re.M)
    if n != 1:
        sys.exit('gen_sga4_shim: macros.tex: \\showgitstatus was not found once.')
    macros = drop_lines(macros, [(r'\\setmainlanguage\b', 1), (r'\\setotherlanguage\b', 1), (r'\\setmathfont\b', 1)], 'macros.tex')
    found, bad, files, size = scan_sources(args.sources)
    table = unicode_table()
    declared = {c: n for c, n in found.items() if c in table}
    unmapped = {c: n for c, n in found.items() if c not in table and not latin1_and_friends(c)}
    decls = '\n'.join(f'\\DeclareUnicodeCharacter{{{c:04X}}}{{{table[c]}}}' for c in sorted(declared))
    os.makedirs(args.out, exist_ok=True)
    paq = os.path.join(args.out, 'paquets.tex')
    with open(paq, 'w', encoding='utf-8') as f:
        f.write('% pdfLaTeX stand-in, generated by tests/corpus/gen_sga4_shim.py --french.  For corpus testing only.\n'
                + FR_HEADER + paquets + '\n' + decls + '\n')
    mac = os.path.join(args.out, 'macros.tex')
    with open(mac, 'w', encoding='utf-8') as f:
        f.write(macros)
    prelude = ('\\makeatletter'
               f'\\declare@file@substitution{{{FR_CONFIG}/paquets.tex}}{{{paq}}}'
               f'\\declare@file@substitution{{{FR_CONFIG}/macros.tex}}{{{mac}}}'
               '\\makeatother ')
    with open(os.path.join(args.out, 'prelude.txt'), 'w') as f:
        f.write(prelude)
    print(f'{args.out}: {files} .tex files, {size} bytes; {len(found)} distinct non-ASCII characters: {len(declared)} declared, '
          f'{len(unmapped)} unmapped {[f"U+{c:04X}" for c in unmapped]}; {bad} undecodable')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--french', action='store_true', help='stand-ins for the French originals instead')
    ap.add_argument('--sources', help='directory holding the macro file and the .tex sources')
    ap.add_argument('--out')
    args = ap.parse_args()
    args.sources = args.sources or (DEFAULT_FR_SOURCES if args.french else DEFAULT_SOURCES)
    args.out = args.out or (DEFAULT_FR_OUT if args.french else DEFAULT_OUT)
    if args.french:
        french(args)
        return
    sty = os.path.join(args.sources, 'sga4-en.sty')
    with open(sty, encoding='utf-8') as f:
        original = f.read()
    found, bad, files, size = scan_sources(args.sources)
    table = unicode_table()
    declared, unmapped, default = {}, {}, {}
    for cp, n in sorted(found.items()):
        if cp in table:
            declared[cp] = n
        elif latin1_and_friends(cp):
            default[cp] = n
        else:
            unmapped[cp] = n
    decls = [f'\\DeclareUnicodeCharacter{{{cp:04X}}}{{{table[cp]}}}' for cp in sorted(declared)]
    text = transform(original)
    mark = '\\endinput'
    tail = text.rfind(mark)
    if tail < 0:
        sys.exit('gen_sga4_shim: the original has no \\endinput')
    block = '% --- characters used by the sources, declared by the generator ---\n' + '\n'.join(decls) + '\n\n'
    text = text[:tail] + block + text[tail:]
    os.makedirs(args.out, exist_ok=True)
    out = os.path.join(args.out, 'sga4-en.sty')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    report = {'sources': args.sources, 'tex_files': files, 'tex_bytes': size, 'undecodable_chars': bad,
              'non_ascii_distinct': len(found), 'non_ascii_total': sum(found.values()),
              'declared_by_shim': {f'U+{c:04X}': n for c, n in declared.items()},
              'left_to_latex_defaults': {f'U+{c:04X}': n for c, n in default.items()},
              'unmapped_stay_errors': {f'U+{c:04X}': n for c, n in unmapped.items()}, 'output': out}
    with open(os.path.join(args.out, 'report.json'), 'w') as f:
        json.dump(report, f, indent=1, sort_keys=True)
    print(f'{out}: {files} .tex files, {size} bytes; {len(found)} distinct non-ASCII characters: {len(declared)} declared, '
          f'{len(default)} left to LaTeX defaults, {len(unmapped)} unmapped {[f"U+{c:04X}" for c in unmapped]}; {bad} undecodable')


if __name__ == '__main__':
    main()
