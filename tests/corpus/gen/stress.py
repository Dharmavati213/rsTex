r"""Scaling cases: long paragraphs, deep nesting up to the limits, big macros, many names, huge alignments, many pages.

Every case is compared like the others and doubles as a performance case (run.py bench --filter coverage/stress).  Tracing stays off so
logs stay small.  The capacity-* cases hit a limit from texmf.cnf and end the job: a candidate that keeps those limits matches, and one
with larger capacities differs on those entries by design, which the notes say.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))     # python3 -I leaves the script directory off the path
from common import clean_category, entry, write_doc
from fuzz import Rng, WORDS

HEAD = r"""% generated by tests/corpus/gen/stress.py
\hsize=300pt \vsize=500pt \tolerance=500 \hfuzz=\maxdimen \vfuzz=\maxdimen \hbadness=10000 \vbadness=10000
\catcode`\@=11
"""
LOOP = r"""\newcount\n \newcount\m
"""


def words(seed, n, per_line=12):
    r = Rng(seed)
    lines = []
    for i in range(0, n, per_line):
        lines.append(' '.join(r.choice(WORDS) for _ in range(min(per_line, n - i))))
    return '\n'.join(lines)


def nested(open_tok, close_tok, n, inner=''):
    return (open_tok * n) + inner + (close_tok * n)


def cases():
    yield 'long-paragraph-100k', HEAD + words(1, 100000) + '\\par\n\\end\n', {}, 'a paragraph of 100000 words'
    yield 'long-paragraph-narrow', HEAD + '\\hsize=40pt \\emergencystretch=20pt ' + words(2, 30000) + '\\par\n\\end\n', {}, 'a paragraph of 30000 words in a narrow measure, with many hyphenation attempts'
    yield 'long-paragraph-tolerant', HEAD + '\\tolerance=9999 ' + words(3, 10000) + '\\par\n\\end\n', {}, 'a paragraph of 10000 words with \\tolerance=9999, so the active list grows large'
    yield 'long-paragraph-math', HEAD + ''.join(f'word $x_{{{i % 10}}}^2+y={i}$ ' + ('\n' if i % 8 == 0 else '') for i in range(20000)) + '\\par\n\\end\n', {}, '20000 inline formulas in one paragraph'
    yield 'many-paragraphs', HEAD + ''.join(words(i, 40) + '\n\n' for i in range(5000)) + '\\end\n', {}, '5000 paragraphs of 40 words with page building'
    for n in (100, 254, 255):
        yield f'deep-braces-{n}', HEAD + nested('{', '}', n, '\\showthe\\currentgrouplevel ') + '\n\\end\n', {}, f'{n} nested brace groups'
        yield f'deep-begingroup-{n}', HEAD + nested('\\begingroup', '\\endgroup', n, '\\showthe\\currentgrouplevel ') + '\n\\end\n', {}, f'{n} nested \\begingroup'
    yield 'capacity-grouping-256', HEAD + nested('{', '}', 256) + '\n\\end\n', {}, 'one level over the limit of 255: the error is fatal. A candidate with wider quarterwords must still report it'
    yield 'capacity-begingroup-300', HEAD + nested('\\begingroup', '\\endgroup', 300) + '\n\\end\n', {}, 'over the grouping limit with \\begingroup'
    yield 'deep-hbox-200', HEAD + nested('\\hbox{', '}', 200, 'x') + '\n\\end\n', {}, '200 nested boxes'
    yield 'deep-vbox-200', HEAD + '\\setbox1=' + nested('\\vbox{', '}', 200, '\\hbox{x}') + '\\shipout\\box1\n\\end\n', {}, '200 nested vboxes, shipped out'
    yield 'deep-if-100k', HEAD + '\\iftrue' * 100000 + '\\message{inside}' + '\\fi' * 100000 + '\n\\end\n', {}, '100000 nested conditionals, taken'
    yield 'deep-if-skipped-100k', HEAD + '\\iffalse' + '\\iftrue' * 100000 + '\\fi' * 100000 + '\\fi\\message{after}\n\\end\n', {}, '100000 nested conditionals, skipped'
    yield 'deep-math-fractions', HEAD + '$$' + nested('{1\\over ', '}', 200, 'x') + '$$\n\\end\n', {}, '200 nested fractions'
    yield 'tail-recursion-100k', HEAD + r"""\def\a#1{\ifnum#1>0 \expandafter\a\expandafter{\number\numexpr#1-1\expandafter}\fi}\a{100000}\message{done}
\end
""", {}, '100000 steps of tail recursion through \\expandafter'
    yield 'capacity-input-stack', HEAD + r"""\def\b{\b x}\b
\end
""", {}, 'non-tail recursion: input stack overflow, fatal'
    yield 'capacity-expand-depth', HEAD + r"""\def\e{\number\e}\e
\end
""", {}, 'expansion depth overflow: expansion nested inside scanning a number, fatal'
    yield 'capacity-param-stack', HEAD + r"""\def\p#1#2#3#4#5#6#7#8#9{\p123456789x}\p123456789
\end
""", {}, 'parameter stack overflow: nine parameters per level, fatal'
    yield 'capacity-main-memory', HEAD + r"""\def\g#1{\g{#1#1}}\g{aaaaaaaaaaaaaaaa}
\end
""", {}, 'main memory overflow by doubling a macro argument, fatal. A candidate with a larger memory differs by design'
    yield 'capacity-save-stack', HEAD + r"""\newcount\n \begingroup \loop\ifnum\n<250000 \expandafter\let\csname s\number\n\endcsname=\relax \advance\n by 1 \repeat \endgroup
\end
""", {}, 'save stack overflow from local assignments to distinct names, fatal'
    yield 'capacity-hash', HEAD + r"""\newcount\n \loop\ifnum\n<700000 \expandafter\let\csname h\number\n\endcsname=\relax \advance\n by 1 \repeat
\end
""", {}, 'many names: the string limit is hit before the hash limit, fatal. A candidate with larger tables differs by design'
    yield 'capacity-buffer', HEAD + 'x' * 300000 + '\\par\n\\end\n', {}, 'an input line over buf_size: the exit status is what remains to compare, since the message goes to the terminal'
    yield 'long-line-199k', HEAD + '\\setbox0=\\hbox{\\nullfont ' + 'x ' * 99500 + '}\n\\end\n', {}, 'an input line just under buf_size'
    token = 'abcdefghij'
    body = '\n'.join(token * 10 for _ in range(10000))
    yield 'million-token-macro', HEAD + '\\tracinglostchars=0 \\endlinechar=-1 \\def\\big{\n' + body + '\n}\\endlinechar=13 \n' + r"""\edef\c{\big}\def\take#1{}\expandafter\take\expandafter{\c}\ifx\c\big\message{same}\else\message{different}\fi\let\c=\relax
\edef\d{\detokenize\expandafter{\big}}\ifx\d\big\message{same}\else\message{different}\fi\let\d=\relax
\toks0=\expandafter{\big}\edef\e{\the\toks0}\ifx\e\big\message{same}\else\message{different}\fi\let\e=\relax
\setbox0=\hbox{\nullfont\big}\message{\the\wd0}
\end
""", {}, 'a macro of 1000000 character tokens: copied, passed as an argument, detokenized, run through main control'
    yield 'csname-100k', HEAD + LOOP + r"""\loop\ifnum\n<100000 \expandafter\def\csname k\number\n\endcsname{\number\n}\advance\n by 1 \repeat
\n=0 \m=0 \loop\ifnum\n<100000 \advance\m by\csname k\number\n\endcsname\relax \advance\n by 1 \repeat
\message{\the\m}\expandafter\show\csname k99999\endcsname
\end
""", {}, '100000 \\csname entries, defined and read back'
    yield 'hash-collisions', HEAD + LOOP + r"""\loop\ifnum\n<50000 \expandafter\let\csname\romannumeral\n\endcsname=\relax \advance\n by 1 \repeat
\end
""", {}, '50000 long and similar names from \\romannumeral'
    rows = ''.join('&'.join(f'c{r}x{c}' for c in range(10)) + '\\cr\n' for r in range(5000))
    yield 'huge-halign', HEAD + '\\halign{' + '&'.join(['\\hfil#\\hfil\\tabskip=1pt plus 1pt'] * 10) + '\\cr\n' + rows + '}\n\\end\n', {}, 'a \\halign of 5000 rows and 10 columns'
    yield 'wide-halign', HEAD + '\\font\\tiny=cmr5 at 1pt \\tiny\\baselineskip=2pt \\hsize=16000pt \\halign{&#\\tabskip=0pt\\cr\n' + '&'.join('i' for c in range(3000)) + '\\cr\n}\n\\end\n', {}, 'a \\halign with 3000 columns'
    yield 'huge-valign', HEAD + '\\setbox0=\\hbox{\\valign{&#\\vfil\\cr\n' + ''.join('\\hbox{a}&\\hbox{b}&\\hbox{c}\\cr\n' for _ in range(2000)) + '}}\\shipout\\box0\n\\end\n', {}, 'a \\valign of 2000 rows, in a box too wide to ship, which is reported'
    yield 'shipout-10k', HEAD + LOOP + r"""\loop\ifnum\n<10000 \shipout\hbox{page \number\n}\advance\n by 1 \repeat
\end
""", {}, '10000 pages by \\shipout'
    yield 'pages-10k', HEAD + LOOP + r"""\vsize=100pt \output={\shipout\box255 \advance\count0 by 1 }
\loop\ifnum\n<10000 \hbox{line \number\n}\hbox{second}\penalty-10000 \advance\n by 1 \repeat
\end
""", {}, '10000 pages through the page builder and an output routine'
    yield 'pages-plain-3k', HEAD + LOOP + r"""\output={\plainoutput}\vsize=100pt \footline={\hss\tenrm\folio\hss}\headline={\hfil\tenbf head}
\loop\ifnum\n<3000 \noindent one two three\endgraf\vfill\eject\advance\n by 1 \repeat
\end
""", {}, "3000 pages with plain's own output routine"
    yield 'long-vlist', HEAD + LOOP + r"""\setbox1=\vbox{\loop\ifnum\n<200000 \hbox{}\advance\n by 1 \repeat}\message{\the\ht1}
\setbox2=\vsplit1 to 1000pt \message{\the\ht1}\message{\the\ht2}
\end
""", {}, 'a vbox of 200000 lines, then \\vsplit'
    yield 'long-hlist', HEAD + LOOP + r"""\setbox1=\hbox{\loop\ifnum\n<200000 x\advance\n by 1 \repeat}\message{\the\wd1}\shipout\box1
\end
""", {}, 'an hbox of 200000 characters, whose width wraps past the 32-bit limit: too wide to ship, which is reported'
    yield 'many-fonts-1000', HEAD + LOOP + r"""\loop\ifnum\n<1000 \advance\n by 1 \font\f=cmr10 at \number\n sp \relax \font\g=cmr10 at \numexpr\n+65536\relax sp \setbox0=\hbox{\g a}\ifnum\n<5 \shipout\box0 \fi \repeat
\shipout\hbox{\g last}
\end
""", {}, '2000 font instances at different sizes'
    yield 'many-registers', HEAD + LOOP + r"""\loop\ifnum\n<32768 \count\n=\n \dimen\n=\n sp \skip\n=\n sp \muskip\n=1mu \toks\n={x}\setbox\n=\hbox{}\marks\n{y}\advance\n by 1 \repeat
\n=32767 \message{\the\count\n,\the\dimen\n,\the\skip\n,\the\muskip\n,\the\toks\n}
\vfill\penalty-10000 \message{\topmarks32767,\firstmarks32767,\botmarks32767}
\end
""", {}, 'every register of every kind, and every marks class'
    yield 'many-objects', HEAD + LOOP + r"""\loop\ifnum\n<100000 \immediate\pdfobj {<</N \number\n>>}\advance\n by 1 \repeat
\shipout\hbox{a}
\end
""", {}, '100000 PDF objects'
    yield 'many-dests', HEAD + LOOP + r"""\baselineskip=0pt \lineskip=0pt \lineskiplimit=-\maxdimen \shipout\vbox{\loop\ifnum\n<20000 \pdfdest name {dest\number\n} fit \hbox{}\advance\n by 1 \repeat}
\n=0 \loop\ifnum\n<2000 \pdfoutline goto name {dest\number\n} {Item \number\n}\advance\n by 1 \repeat
\end
""", {}, '20000 named dests and 2000 outline items'
    yield 'many-links', HEAD + LOOP + r"""\loop\ifnum\n<3000 \shipout\hbox{\pdfstartlink goto page 1 {/Fit} x\pdfendlink\pdfannot width 1pt {/Subtype /Text}\pdfliteral{q Q}}\advance\n by 1 \repeat
\end
""", {}, '3000 pages with a link, an annotation and a literal'
    yield 'many-xforms', HEAD + LOOP + r"""\loop\ifnum\n<3000 \setbox0=\hbox{form \number\n}\immediate\pdfxform 0 \shipout\hbox{\pdfrefxform\pdflastxform}\advance\n by 1 \repeat
\end
""", {}, '3000 form XObjects'
    yield 'many-hyphenations', HEAD + LOOP + r"""\def\w{\number\n}\lccode`0=`0 \lccode`1=`1 \lccode`2=`2 \lccode`3=`3 \lccode`4=`4 \lccode`5=`5 \lccode`6=`6 \lccode`7=`7 \lccode`8=`8 \lccode`9=`9
\loop\ifnum\n<8000 \hyphenation{a-\number\n}\advance\n by 1 \repeat
\end
""", {}, '8000 hyphenation exceptions'
    yield 'long-write', HEAD + LOOP + r"""\immediate\openout1=big.out \def\s{0123456789}\def\t{\s\s\s\s\s\s\s\s\s\s}\def\u{\t\t\t\t\t\t\t\t\t\t}
\loop\ifnum\n<2000 \immediate\write1{\u}\advance\n by 1 \repeat\immediate\closeout1
\end
""", {}, '2000 long \\write lines'
    yield 'long-math-list', HEAD + '$$' + ' '.join('a+b' for _ in range(20000)) + '$$\n\\end\n', {}, 'a display with 60000 atoms'
    yield 'numexpr-loop', HEAD + LOOP + r"""\loop\ifnum\n<1000000 \advance\n by 1 \m=\numexpr(\m+\n*3)/2\relax \repeat\message{\the\m}
\end
""", {}, '1000000 expression evaluations'
    yield 'expandafter-chain', HEAD + LOOP + r"""\def\a{}\loop\ifnum\n<2000 \expandafter\def\expandafter\a\expandafter{\a x}\advance\n by 1 \repeat
\edef\b{\a}\message{\the\numexpr 1\relax}
\end
""", {}, 'quadratic token list growth'


# The cases too slow for the standard tier; the rest are candidates for it.
EXPENSIVE = {'long-paragraph-100k', 'long-paragraph-tolerant', 'long-line-199k', 'long-paragraph-math', 'long-paragraph-narrow', 'many-paragraphs', 'shipout-10k', 'pages-10k', 'pages-plain-3k', 'huge-halign', 'many-registers',
             'many-objects', 'many-dests', 'many-links', 'many-xforms', 'capacity-hash', 'capacity-save-stack', 'capacity-main-memory', 'capacity-param-stack',
             'csname-100k', 'hash-collisions', 'numexpr-loop', 'million-token-macro', 'long-vlist', 'long-hlist', 'long-write', 'long-math-list', 'many-fonts-1000', 'wide-halign', 'huge-valign'}


def generate():
    entries, names = [], []
    for name, text, fields, note in cases():
        names.append(name)
        main = write_doc('stress', name, text)
        e = entry(f'coverage/stress/{name}', main, timeout=600, notes=note, **fields)
        if name in EXPENSIVE:
            e['expensive'] = True
        entries.append(e)
    clean_category('stress', names)
    exclusions = [{'what': 'the capacity-* stress entries compare a limit from texmf.cnf, not a typesetting result',
                   'why': 'A candidate with a growable memory (DESIGN section 4) is expected to differ on capacity-main-memory, capacity-hash and capacity-save-stack. They stay in the denominator and in every report. Grouping levels, the input stack and the expansion depth are limits documents can see.'}]
    return entries, exclusions, {'stress': len(entries)}
