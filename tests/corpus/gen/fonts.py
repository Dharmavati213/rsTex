"""Every font in pdftex.map: the full 256-character table, one page per font, batched at 50 fonts per document.

The map is larger than the installed fonts here: many entries have no .tfm, and a few have no .pfb or .enc.  So:

  table-NNNN    fonts with a .tfm, reached through the pdftex.map lookup.
  mapline-NNNN  the same fonts, with every line also given to \\pdfmapline.
  notfm-NNNN    fonts without a .tfm: \\font must fail with the same message.
  stub-NNNN     the same fonts with a copy of ecrm1000.tfm under their name in the document's directory.  TeX has metrics and
                pdfTeX then really reads the .pfb and .enc of that map line, which is what these tests are after.
  expansion-N   font expansion and protrusion on a sample.
  alone-NAME    a font sharing a PostScript name with an earlier map entry but with its own file; in a batch pdfTeX would not read it.

Which fonts kill the oracle (a missing .pfb or .enc is fatal for the whole document) is found by compiling each font alone, once,
and is kept in target/corpus/gen/font/plan.json until pdftex.map changes.  A font that kills the oracle gets a document of its own,
so the rest of its batch still reaches its table.  Each page is a unit, and run.py maps a divergent page or log line back to the font."""
import concurrent.futures as cf
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))     # python3 -I leaves the script directory off the path
from common import GEN_ROOT, clean_category, entry, run_pdftex, write_doc, write_json

MAP = '/var/lib/texmf/fonts/map/pdftex/updmap/pdftex.map'
BATCH = 50
SAMPLE_EVERY = 25          # font expansion and protrusion: every 25th mapped font that really loads
EXPAND_BATCH = 10
STUB_TFM = 'ecrm1000.tfm'  # 256 characters, so the whole table is asked of the font file

PREAMBLE = r"""% generated by tests/corpus/gen/fonts.py
\tracinglostchars=1 \hbadness=10000 \vbadness=10000 \hfuzz=\maxdimen \vfuzz=\maxdimen
\newcount\ci \newcount\cn \newcount\cw \newcount\ch \newcount\cd \newcount\cx
\def\cell{\hbox to 18pt{\hss\iffontchar\testfont\ci \char\ci \fi\hss}\global\advance\ci by 1 }
\def\sixteen{\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell\cell}
\def\strutrule{\vrule height 14pt depth 4pt width 0pt }
\def\tablerows{\global\ci=0
  \loop\ifnum\ci<256 \hbox{\strutrule\testfont\sixteen}\repeat}
\def\metrics#1{\ci=0 \cn=0 \cw=0 \ch=0 \cd=0 \cx=0
  \loop\ifnum\ci<256
    \iffontchar\testfont\ci \advance\cn by 1
      \advance\cw by\fontcharwd\testfont\ci \advance\ch by\fontcharht\testfont\ci
      \advance\cd by\fontchardp\testfont\ci \advance\cx by\fontcharic\testfont\ci \fi
    \advance\ci by 1 \repeat
  \immediate\write-1{#1: chars=\the\cn\space wd=\the\cw\space ht=\the\ch\space dp=\the\cd\space ic=\the\cx
    \space name=\fontname\testfont\space hyph=\the\hyphenchar\testfont\space skew=\the\skewchar\testfont}%
  \ifx\testfont\nullfont\else
    \immediate\write-1{#1: fontdimen \the\fontdimen1\testfont\space \the\fontdimen2\testfont\space \the\fontdimen3\testfont
      \space \the\fontdimen4\testfont\space \the\fontdimen5\testfont\space \the\fontdimen6\testfont\space \the\fontdimen7\testfont}%
  \fi}
\def\fontpage#1{\immediate\write-1{[[unit #1]]}%
  \font\testfont=#1 at 8pt \relax
  \metrics{#1}%
  \shipout\vbox{\offinterlineskip \hbox{\strutrule\tenrm\detokenize{#1}}\tablerows}}
"""

EXPAND_PREAMBLE = r"""% generated by tests/corpus/gen/fonts.py
\tracingparagraphs=1 \tracingonline=1 \showboxbreadth=100 \showboxdepth=100 \tracinglostchars=1 \hbadness=10000
\hsize=150pt \tolerance=9999 \emergencystretch=5pt \parindent=0pt \pdfadjustspacing=2 \pdfprotrudechars=2
\newcount\ci
\def\codes#1{\ci=0 \loop\ifnum\ci<256 \efcode#1\ci=800 \rpcode#1\ci=120 \lpcode#1\ci=80
    \advance\ci by 1 \repeat
  \rpcode#1`\.=700 \rpcode#1`\,=500 \lpcode#1`A=50 \efcode#1`i=300 }
\def\sample{Typography is the art of arranging type, and hanging punctuation, margin kerning and
  font expansion make justified lines look even. Office affluent difficult waffle efficient, the quick
  brown fox jumps over the lazy dog. AVAILABLE WATER Tokyo.\par}
\def\fontsample#1{\immediate\write-1{[[unit #1]]}%
  \font\testfont=#1 at 10pt \relax
  \codes\testfont
  \pdffontexpand\testfont 25 25 5 autoexpand \relax
  \setbox0=\vbox{\testfont\sample}\showbox0
  \setbox1=\vbox{\testfont\pdfadjustspacing=1 \sample}\showbox1
  \setbox2=\vbox{\testfont\pdfprotrudechars=1 \pdfadjustspacing=0 \sample}\showbox2
  \setbox3=\vbox{\unvcopy0 \setbox4=\lastbox\immediate\write-1{margin kerns: \rightmarginkern4 \leftmarginkern4 }}%
  \shipout\box0 \shipout\box1 \shipout\box2 }
"""


def read_map():
    """(ordered tfm names, {tfm: map line}, duplicate names).  Comment and blank lines are not entries."""
    names, lines, dups = [], {}, []
    with open(MAP, 'rb') as f:
        for raw in f.read().decode('latin-1').split('\n'):
            line = raw.strip()
            if not line or line[0] in '%#*;':
                continue
            tfm = line.split()[0]
            if tfm in lines:
                dups.append(tfm)
                continue
            names.append(tfm)
            lines[tfm] = line
    return names, lines, dups


def table_doc(fonts, lines, with_mapline=False):
    out = [PREAMBLE]
    if with_mapline:
        out.append('% every map line given again with \\pdfmapline, on top of pdftex.map\n')
        for t in fonts:
            out.append('\\pdfmapline{=%s}\n' % lines[t])
    for t in fonts:
        out.append('\\fontpage{%s}\n' % t)
    out.append('\\end\n')
    return ''.join(out)


def expand_doc(fonts):
    return EXPAND_PREAMBLE + ''.join('\\fontsample{%s}\n' % t for t in fonts) + '\\end\n'


def tfm_names():
    """TFM names kpathsea can find, from the ls-R databases; the map's own names are then a set membership test."""
    found = set()
    for root in ('/usr/share/texmf-dist', '/var/lib/texmf', '/usr/share/texmf', '/etc/texmf'):
        try:
            with open(os.path.join(root, 'ls-R'), 'rb') as f:
                for raw in f.read().split(b'\n'):
                    if raw.endswith(b'.tfm'):
                        found.add(raw[:-4].decode('latin-1'))
        except OSError:
            pass
    return found


FLAKES = []


def try_once(text, stubs, stub_bytes, work):
    d = tempfile.mkdtemp(dir=work)
    try:
        src = os.path.join(d, 'doc.tex')
        with open(src, 'w', encoding='latin-1') as f:
            f.write(text)
        for t in stubs:
            with open(os.path.join(d, t + '.tfm'), 'wb') as f:
                f.write(stub_bytes)
        rc, log = run_pdftex(src, os.path.join(d, 'o'), timeout=180)
        return rc is not None and os.path.isfile(os.path.join(d, 'o', 'doc.pdf')), rc, log
    finally:
        shutil.rmtree(d, ignore_errors=True)


def try_doc(text, stubs, stub_bytes, work):
    """True when the oracle gets through this document and writes a PDF.  A failure must repeat to count: a loaded machine can
    fail a run for reasons that have nothing to do with the document, and a font must not lose its place in a batch for that."""
    ok, rc, log = try_once(text, stubs, stub_bytes, work)
    if ok:
        return True
    ok, _, _ = try_once(text, stubs, stub_bytes, work)
    if ok:
        FLAKES.append({'rc': rc, 'tail': log[-600:].decode('latin-1')})
    return ok


def chunks(items, n):
    return [items[i:i + n] for i in range(0, len(items), n)]


def group(fonts, fatal):
    """Batches of the fonts that compile, in map order, then each fatal font in a document of its own."""
    good = [t for t in fonts if t not in fatal]
    return chunks(good, BATCH) + [[t] for t in fonts if t in fatal]


def bisect(fonts, make_doc, stubs, stub_bytes, work):
    """A batch of individually fine fonts that still fails together is split until each piece compiles."""
    if try_doc(make_doc(fonts), stubs, stub_bytes, work) or len(fonts) == 1:
        return [fonts]
    mid = len(fonts) // 2
    return (bisect(fonts[:mid], make_doc, fonts[:mid] if stubs else [], stub_bytes, work)
            + bisect(fonts[mid:], make_doc, fonts[mid:] if stubs else [], stub_bytes, work))


def stub_bytes_of():
    p = subprocess.run(['kpsewhich', STUB_TFM], capture_output=True, text=True).stdout.strip()
    with open(p, 'rb') as f:
        return f.read()


def make_plan(names, lines, jobs):
    os.makedirs(os.path.join(GEN_ROOT, 'font'), exist_ok=True)
    path = os.path.join(GEN_ROOT, 'font', 'plan.json')
    with open(MAP, 'rb') as f:
        h = hashlib.sha256(f.read())
    h.update((PREAMBLE + EXPAND_PREAMBLE).encode())
    h.update(str(BATCH).encode())
    digest = h.hexdigest()
    try:
        with open(path) as f:
            plan = json.load(f)
        if plan['digest'] == digest:
            return plan
    except (OSError, ValueError, KeyError):
        pass
    tfms = tfm_names()
    with_tfm = [t for t in names if t in tfms]
    without = [t for t in names if t not in tfms]
    stub = stub_bytes_of()
    work = tempfile.mkdtemp(dir=os.path.join(GEN_ROOT, 'font'), prefix='.plan-')
    try:
        with cf.ThreadPoolExecutor(jobs) as ex:
            ok = dict(zip(with_tfm, ex.map(lambda t: try_doc(table_doc([t], lines), [], stub, work), with_tfm)))
            stub_ok = dict(zip(without, ex.map(lambda t: try_doc(table_doc([t], lines), [t], stub, work), without)))
        fatal = {t for t, v in ok.items() if not v}
        stub_fatal = {t for t, v in stub_ok.items() if not v}
        if len(fatal) > len(with_tfm) / 5 or len(stub_fatal) > len(without) / 2:
            raise SystemExit(f'{len(fatal)} of {len(with_tfm)} fonts and {len(stub_fatal)} of {len(without)} stubs kill the oracle: the document template is broken, not the fonts')
        tables = group(with_tfm, fatal)
        stubs = group(without, stub_fatal)
        with cf.ThreadPoolExecutor(jobs) as ex:
            tables = [p for ps in ex.map(lambda b: bisect(b, lambda f: table_doc(f, lines), [], stub, work)
                                         if b[0] not in fatal else [b], tables) for p in ps]
            stubs = [p for ps in ex.map(lambda b: bisect(b, lambda f: table_doc(f, lines), b, stub, work)
                                        if b[0] not in stub_fatal else [b], stubs) for p in ps]
        loads = [t for t in with_tfm if t not in fatal and ('.pfb' in lines[t] or '.pfa' in lines[t])]
        sample = loads[::SAMPLE_EVERY]
        with cf.ThreadPoolExecutor(jobs) as ex:
            expand_ok = dict(zip(sample, ex.map(lambda t: try_doc(expand_doc([t]), [], stub, work), sample)))
        if sum(1 for v in expand_ok.values() if not v) > len(sample) / 5:
            raise SystemExit('most of the expansion sample kills the oracle: the document template is broken, not the fonts')
        expansion = chunks([t for t in sample if expand_ok[t]], EXPAND_BATCH) + [[t] for t in sample if not expand_ok[t]]
    finally:
        shutil.rmtree(work, ignore_errors=True)
    plan = {'digest': digest, 'flakes': FLAKES, 'with_tfm': with_tfm, 'without_tfm': without, 'fatal': sorted(fatal), 'stub_fatal': sorted(stub_fatal),
            'tables': tables, 'stubs': stubs, 'expansion': expansion, 'expansion_fatal': sorted(t for t, v in expand_ok.items() if not v)}
    write_json(path, plan)
    return plan


def generate(jobs=8):
    names, lines, dups = read_map()
    plan = make_plan(names, lines, jobs)
    entries, keep, reached = [], [], []
    fatal, stub_fatal = set(plan['fatal']), set(plan['stub_fatal'])
    for i, fonts in enumerate(plan['tables']):
        reached += fonts
        dead = fonts[0] in fatal
        note = f'{len(fonts)} fonts, {fonts[0]} to {fonts[-1]}' + ('; alone because the oracle dies on it' if dead else '')
        for kind, with_mapline in (('table', False), ('mapline', True)):
            name = f'{kind}-{i:04d}'
            keep.append(name)
            main = write_doc('font', name, table_doc(fonts, lines, with_mapline))
            entries.append(entry(f'coverage/font/{name}', main, units=fonts, timeout=300, notes=note))
    for i, fonts in enumerate(chunks(plan['without_tfm'], BATCH)):
        name = f'notfm-{i:04d}'
        keep.append(name)
        main = write_doc('font', name, table_doc(fonts, lines))
        entries.append(entry(f'coverage/font/{name}', main, units=fonts, timeout=300,
                             notes=f'{len(fonts)} fonts with no .tfm installed: every \\font fails the same way, {fonts[0]} to {fonts[-1]}'))
    stub = stub_bytes_of()
    for i, fonts in enumerate(plan['stubs']):
        reached += fonts
        name = f'stub-{i:04d}'
        keep.append(name)
        main = write_doc('font', name, table_doc(fonts, lines))
        for t in fonts:
            write_doc('font', name, stub, filename=t + '.tfm')
        dead = fonts[0] in stub_fatal
        entries.append(entry(f'coverage/font/{name}', main, units=fonts, timeout=300,
                             notes=f'{len(fonts)} fonts, metrics from a copy of {STUB_TFM}, font file from the map line, {fonts[0]} to {fonts[-1]}'
                                   + ('; alone because the oracle dies on it' if dead else '')))
    if sorted(reached) != sorted(names):
        raise SystemExit('a mapped font fell out of the batches')
    # pdfTeX shares one font descriptor between map entries with the same PostScript name, so in a batch only the first entry's
    # font file is read.  Where the files differ, each later entry also gets a document of its own, so its file is read too.
    first_file, alone = {}, []
    for t in names:
        parts = lines[t].split()
        ps = parts[1] if len(parts) > 1 and not parts[1].startswith(('<', '"')) else t
        files = re.findall(r'<<?\[?([^\s<]+\.pf[ab])', lines[t])
        if files:
            if first_file.setdefault(ps, files[0]) != files[0] and t not in fatal and t not in stub_fatal:
                alone.append(t)
    with_tfm_set = set(plan['with_tfm'])
    for t in alone:
        name = f'alone-{t}'
        keep.append(name)
        main = write_doc('font', name, table_doc([t], lines))
        if t not in with_tfm_set:
            write_doc('font', name, stub, filename=t + '.tfm')
        entries.append(entry(f'coverage/font/{name}', main, units=[t], timeout=300,
                             notes='shares its PostScript name with an earlier map entry but has its own font file'))
    sampled = 0
    for i, fonts in enumerate(plan['expansion']):
        name = f'expansion-{i:04d}'
        keep.append(name)
        sampled += len(fonts)
        main = write_doc('font', name, expand_doc(fonts))
        # Three pages per font: both expansion settings and protrusion alone.
        entries.append(entry(f'coverage/font/{name}', main, units=[t for t in fonts for _ in range(3)], timeout=300,
                             notes='font expansion and protrusion' + ('; the oracle dies on this font' if fonts[0] in plan['expansion_fatal'] else '')))
    clean_category('font', keep)
    exclusions = [
        {'what': f'font expansion and protrusion run on a sample of {sampled} of {len(names)} mapped fonts (every {SAMPLE_EVERY}th that loads and has a font file)',
         'why': 'The paragraph machinery is common code; the sample exercises it across formats and encodings. Every mapped font still gets its full table.'},
        {'what': f'{len(plan["without_tfm"])} map entries have no .tfm in this TeX Live; their table runs on a stub .tfm (a copy of {STUB_TFM}) in the document directory',
         'why': f'Without metrics TeX cannot load them. The real path is tested too: notfm documents must fail with the same message on every font. {len(plan["stub_fatal"])} of them also have no font file or encoding and are fatal on the oracle.'},
        {'what': f'{len(plan["fatal"])} map entries with a .tfm are fatal on the oracle because a .pfb or .enc is missing; each is alone in its document',
         'why': 'The candidate must die with the same message; these fonts have no table to compare.'},
    ]
    if dups:
        exclusions.append({'what': f'{len(dups)} repeated names in pdftex.map', 'why': 'A later line for the same TFM is the same font; the first line is used.'})
    counts = {'font-map-entries': len(names), 'font-with-tfm': len(plan['with_tfm']), 'font-without-tfm': len(plan['without_tfm']),
              'font-oracle-fatal': len(plan['fatal']), 'font-stub-oracle-fatal': len(plan['stub_fatal']),
              'font-table-docs': len(plan['tables']), 'font-mapline-docs': len(plan['tables']), 'font-stub-docs': len(plan['stubs']),
              'font-notfm-docs': len(chunks(plan['without_tfm'], BATCH)), 'font-expansion-docs': len(plan['expansion']), 'font-expansion-fonts': sampled, 'font-alone-docs': len(alone),
              'font-entries': len(entries)}
    return entries, exclusions, counts


if __name__ == '__main__':
    print(generate()[2])
