#!/usr/bin/env -S python3 -I
r"""Generates crates/engine/src/native_font_table.in: what the native \pickup@font knows about the installed microtype and LaTeX.  crates/engine/src/native_font.rs says what it does with it.

    cargo build --release -p rstex --features rstex-engine/commute-probe --target-dir target/native/probe
    python3 -I tests/native_font/gen_table.py --engine target/native/probe/release/rstex [--check]

Each macro of the cluster, with its hash, as the probe of src/native_probe.rs writes it at the end of a preamble that loads microtype, and hyperref for the hook's other form.  The first name is what decides: a document
whose \pickup@font has another hash has nothing armed.  Run from a directory of its own under the system's temporary one.  --check says whether the file is as it would be written, and changes nothing.

The output depends on the TeX tree, which is why the path is off on any other: the hashes fail, and a run gets slower and no worse.
"""
import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, 'crates', 'engine', 'src', 'native_font_table.in')

# The names, in the order of the path: what runs when a font is known.  native_font.rs looks at MT@setupfont@hook and MT@restore@p@h by themselves.
MACROS = ['pickup@font', 'MT@if@expanding@F', 'MT@if@expanding@F@', '@firstofone', 'MT@let@cn', 'MT@setupfont', 'MT@setupfont@hook', 'MT@restore@p@h', 'MT@exp@two@c', 'MT@split@name', 'MT@fix@fontdimen@six',
          'MT@ifdefined@n@TF', '@firstoftwo', '@secondoftwo', 'MT@exp@one@n', 'MT@find@file', 'MT@in@clist', 'MT@inlist@true', 'MT@check@font', '@empty']
DOCUMENT = r'''\documentclass{article}
\usepackage{microtype}
\usepackage{hyperref}
\AddToHook{begindocument/end}{\message{rstexprobe-safe OUT}}
\begin{document}
\end{document}
'''


def hashes(engine):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, 'macros.txt')
        tex = os.path.join(d, 'x.tex')
        with open(tex, 'w') as f:
            f.write(DOCUMENT.replace('OUT', out))
        env = dict(os.environ, RSTEX_NO_SNAPSHOT='1', RSTEX_NO_COMMUTE='1', RSTEX_NO_PF='1')
        subprocess.run([engine, '-progname=pdflatex', '-interaction=batchmode', '-jobname=x', tex], cwd=d, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=600)
        if not os.path.exists(out):
            sys.exit('no list of macros: is this a build with the feature commute-probe?')
        found = {}
        with open(out, errors='surrogateescape') as f:
            for line in f:
                h, _, name, _ = line.rstrip('\n').split('\t', 3)
                found[name] = h
    missing = [m for m in MACROS if m not in found]
    if missing:
        sys.exit('not defined with microtype loaded: ' + ' '.join(missing))
    return [(m, found[m]) for m in MACROS]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--engine', required=True)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = '// Generated by tests/native_font/gen_table.py.\n[\n' + ''.join('    (b"%s", 0x%s),\n' % row for row in hashes(os.path.abspath(args.engine))) + ']\n'
    if args.check:
        with open(OUT) as f:
            same = f.read() == text
        print('as generated' if same else 'differs from what the installed tree gives')
        return 0 if same else 1
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
