#!/usr/bin/env python3
"""Generates crates/image/src/enc_tables.rs from the tables in xpdf's sources.

Run with python3 -I, giving the directory that holds FontEncodingTables.cc, FoFiEncodings.cc and Stream.cc, from
libs/xpdf/xpdf-src of TeX-Live/texlive-source at the tag in tools/fetch_c_refs.sh (xpdf 4.06, what the oracle links):

    python3 -I tests/oracle/gen_image_enc_tables.py DIR

Those files are data for rstex-image's reading of font encodings and for its Flate decoder, nothing else.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "crates", "image", "src", "enc_tables.rs")


def body(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\[\d*\]\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("no table " + name)
    return re.sub(r"//[^\n]*", "", m.group(1))


def names(src, name, count):
    items = re.findall(r'NULL|"(?:[^"\\]|\\.)*"', body(src, name))
    if len(items) != count:
        raise SystemExit("%s: %d items, wanted %d" % (name, len(items), count))
    return items


def rust_names(rust, items):
    out = ["pub static %s: [Option<&str>; %d] = [" % (rust, len(items))]
    line = "   "
    for it in items:
        cell = " None," if it == "NULL" else " Some(%s)," % it
        if len(line) + len(cell) > 110:
            out.append(line)
            line = "   "
        line += cell
    out.append(line)
    out.append("];")
    return out


def rust_numbers(rust, ty, items):
    out = ["pub static %s: [%s; %d] = [" % (rust, ty, len(items))]
    line = "   "
    for it in items:
        cell = " %s," % it
        if len(line) + len(cell) > 110:
            out.append(line)
            line = "   "
        line += cell
    out.append(line)
    out.append("];")
    return out


def main():
    d = sys.argv[1]
    with open(os.path.join(d, "FontEncodingTables.cc"), encoding="latin-1") as f:
        enc = f.read()
    with open(os.path.join(d, "FoFiEncodings.cc"), encoding="latin-1") as f:
        fofi = f.read()
    with open(os.path.join(d, "Stream.cc"), encoding="latin-1") as f:
        stream = f.read()
    out = [
        "//! Tables from xpdf 4.06 (FontEncodingTables.cc, FoFiEncodings.cc, Stream.cc).  Generated by",
        "//! tests/oracle/gen_image_enc_tables.py; do not edit.",
        "",
    ]
    for rust, c in [("MAC_ROMAN", "macRomanEncoding"), ("MAC_EXPERT", "macExpertEncoding"),
                    ("WIN_ANSI", "winAnsiEncoding"), ("STANDARD", "standardEncoding"),
                    ("SYMBOL", "symbolEncoding"), ("ZAPF_DINGBATS", "zapfDingbatsEncoding")]:
        out += rust_names(rust, names(enc, c, 256))
        out.append("")
    for rust, c in [("FOFI_STANDARD", "fofiType1StandardEncoding"), ("FOFI_EXPERT", "fofiType1ExpertEncoding")]:
        out += rust_names(rust, names(fofi, c, 256))
        out.append("")
    out += rust_names("FOFI_STD_STRINGS", names(fofi, "fofiType1CStdStrings", 391))
    out.append("")
    for rust, c, n in [("CFF_ISO_ADOBE_CHARSET", "fofiType1CISOAdobeCharset", 229),
                       ("CFF_EXPERT_CHARSET", "fofiType1CExpertCharset", 166),
                       ("CFF_EXPERT_SUBSET_CHARSET", "fofiType1CExpertSubsetCharset", 87)]:
        items = re.findall(r"\d+", body(fofi, c))
        if len(items) != n:
            raise SystemExit("%s: %d items" % (c, len(items)))
        out += rust_numbers(rust, "u16", items)
        out.append("")
    for rust, c, n in [("FLATE_FIXED_LIT", "flateFixedLitCodeTabCodes", 512),
                       ("FLATE_FIXED_DIST", "flateFixedDistCodeTabCodes", 32)]:
        pairs = re.findall(r"\{\s*(\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\}", body(stream, c))
        if len(pairs) != n:
            raise SystemExit("%s: %d items" % (c, len(pairs)))
        out += rust_numbers(rust, "(u16, u16)", ["(%s, %s)" % p for p in pairs])
        out.append("")
    with open(OUT, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(out))


main()
