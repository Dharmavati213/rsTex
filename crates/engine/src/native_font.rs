//! A native `\pickup@font`, for a font microtype has set up.  With microtype, this macro runs a cluster of some 25 macros on each `\selectfont`.  For a font it has already set up, all of it is inside
//! `\begingroup...\endgroup`, and everything it assigns goes back at the `\endgroup`: nothing is left of it but ten conditions' nodes, which go through `get_node` and `free_node` as they would, and `cur_val`, `cur_val_level` and `radix`.
//! So when this can prove that is the case, the macro call does just that, and returns with nothing on the input stack.
//!
//! What it has to prove, and where:
//!
//! - **The macros are what they were written as.**  `MACROS`, generated by `tests/native_font/gen_table.py`, holds each with the hash of its tokens, `Tex::native_macro_hash`, one list for each version verified.  All of a list or none: another version of microtype or LaTeX fails a hash and nothing is armed.
//!   The block of each has a reference from here, so the same place proves the same tokens; the check on each call compares places.
//! - **The primitives in their bodies are primitives.**  `PRIMS`, by name and meaning.
//! - **Everything else named in those bodies**, which is only skipped by `pass_text` or only assigned to before it is read, has the class it has as written, `if` for `\\ifMT@inlist@` and neither `if` nor `fi` for all others, and is not outer.
//! - **The font is known**: `\font@name` is one control sequence meaning a font; `MT@subst@<name>` exists and is undefined, so that `\csname` makes no name; `MT@<family>@alias` is not defined, or is plain text;
//!   the family is in `\MT@file@list` and the font in `\MT@font@list`, tested as the delimited match of `\MT@in@clist` tests; `\fontdimen6` is there and not 0.
//! - **Nothing it would have done shows**: no tracing, `\globaldefs` 0, no pending `\afterassignment`, no interrupt, called from the main loop and no other way, no outer name in a list it reads as an argument, room for a group as WEB counts levels and for the depth of expansion, and the marks of `max_in_stack`, `max_param_stack`, `max_save_stack` and
//!   `max_buf_stack` high enough that the real macros would not have raised them.  So a high-water mark in the log's statistics comes from a call that really ran, and the first calls of a run do.
//!
//! The token heap comes out with other blocks free than the macros would have left, and a list's address is in a word of `mem`: the case of docs/PORTING.md section 15.
//!
//! `RSTEX_NO_PF` runs the real macros, and is in a checkpoint's key.  It is not under `--no-commute`, so that `tests/gate.sh`'s compare judges this path against the oracle.  `RSTEX_PF_PEAK` is a test of the margins below, `tests/native_font/run.py`; `RSTEX_PF_STATS` says at the end what became of the calls, and hashes what stays between runs.
#![forbid(unsafe_code)]
#![allow(non_snake_case, unused_mut, unused_imports, dead_code)]

